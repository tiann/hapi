import { expect, test, type Page } from '@playwright/test'

const fixture = '/e2e-fixtures/search-history-fixture.html'
const history = (page: Page) => page.evaluate(() => {
    const key = Object.keys(localStorage).find(key => key.startsWith('hapi.searchHistory.v1.'))
    return key ? JSON.parse(localStorage.getItem(key)!) : null
})
async function go(page: Page, name: string) {
    const labels: Record<string, string> = { Sessions: '会话', Files: '文件', Outline: '大纲', Settings: '设置' }
    await page.getByRole('navigation').getByRole('button', { name: new RegExp(`^(${name}|${labels[name]})$`) }).click()
}
const recent = (page: Page) => page.getByRole('region', { name: 'Recent searches' })
async function optIn(page: Page) {
    await go(page, 'Settings')
    const toggle = page.getByRole('checkbox', { name: /^(Search history|搜索历史)$/ })
    await expect(toggle).not.toBeChecked()
    await toggle.locator('..').click()
    await go(page, 'Sessions')
}

test('fresh browser defaults off and only records after enabling in settings', async ({ page }) => {
    await page.goto(fixture)
    await page.getByRole('searchbox').fill('not saved')
    await page.getByRole('searchbox').press('Enter')
    expect(await history(page)).toBeNull()
    await optIn(page)
    await page.getByRole('searchbox').fill('saved')
    await page.getByRole('searchbox').press('Enter')
    expect((await history(page)).sessions).toEqual(['saved'])
    await page.reload()
    await page.getByRole('searchbox').focus()
    await expect(recent(page).getByRole('button', { name: 'saved', exact: true })).toBeVisible()
})

test('all three production fields persist separate histories, file preview restores the query, and settings manage all lists', async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(fixture)
    await optIn(page)
    const sessions = page.getByRole('searchbox', { name: /^Search sessions/ })
    await sessions.fill('history*')
    expect(await history(page)).toMatchObject({ sessions: [], files: [], outlines: [] })
    await sessions.press('Enter')
    await go(page, 'Files')
    const files = page.getByPlaceholder('Search files')
    await files.fill('README')
    await page.getByRole('button', { name: /README.md/ }).click()
    await expect(page.getByRole('heading', { name: 'File preview' })).toBeVisible()
    await page.getByRole('button', { name: 'Return to files' }).click()
    await expect(files).toHaveValue('README')
    await go(page, 'Outline')
    const outline = page.getByRole('searchbox', { name: 'Search outline items' })
    await outline.fill('*history*')
    await expect(page.getByRole('button', { name: /Implement history/ })).toBeVisible()
    await expect(page.getByRole('button', { name: /Test 中文/ })).toHaveCount(0)
    await page.getByRole('button', { name: 'Close', exact: true }).click()
    expect(await history(page)).toMatchObject({ sessions: ['history*'], files: ['README'], outlines: ['*history*'] })
    await page.reload()
    await sessions.focus()
    await expect(recent(page).getByRole('button', { name: 'history*', exact: true })).toBeVisible()
    await sessions.press('ArrowDown')
    await expect(recent(page).getByRole('button', { name: 'history*', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(sessions).toHaveValue('history*')
    await go(page, 'Settings')
    const toggle = page.getByRole('checkbox', { name: 'Search history', exact: true })
    await expect(toggle).toBeChecked()
    if (process.env.HAPI_TEST_ARTIFACT_DIR) await page.screenshot({ path: `${process.env.HAPI_TEST_ARTIFACT_DIR}/search-history-settings.png`, fullPage: true })
    await toggle.locator('..').click()
    await go(page, 'Files')
    await files.fill('ignored')
    await files.press('Enter')
    expect((await history(page)).files).toEqual(['README'])
    await files.fill('')
    await expect(recent(page)).toHaveCount(0)
    await go(page, 'Settings')
    await toggle.locator('..').click()
    await go(page, 'Files')
    await files.focus()
    await recent(page).getByRole('button', { name: 'Remove search: README' }).click()
    expect((await history(page)).files).toEqual([])
    expect((await history(page)).sessions).toEqual(['history*'])
    await go(page, 'Settings')
    await page.getByRole('button', { name: 'Clear search history', exact: true }).click()
    expect(await history(page)).toEqual({ enabled: true, sessions: [], files: [], outlines: [] })
    await page.reload()
    await sessions.focus()
    await expect(recent(page)).toHaveCount(0)
    expect(errors).toEqual([])
})

