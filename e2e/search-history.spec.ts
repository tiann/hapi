test('composition Enter does not save fragments; completed input and outline close do', async ({ page }) => {
    await page.goto(fixture)
    await optIn(page)
    await go(page, 'Outline')
    const input = page.getByRole('searchbox')
    await input.fill('zhong')
    // Start after fill: Firefox's native fill operation can end a composition.
    await input.dispatchEvent('compositionstart', { data: '' })
    await input.press('Enter')
    expect(await history(page)).toMatchObject({ sessions: [], files: [], outlines: [] })
    await input.fill('中文')
    await input.dispatchEvent('compositionend', { data: '中文' })
    await page.getByRole('button', { name: 'Close', exact: true }).click()
    expect((await history(page)).outlines).toEqual(['中文'])
})

test('blocked storage leaves searching and settings usable', async ({ page }) => {
    await page.addInitScript(() => {
        const getItem = Storage.prototype.getItem
        Storage.prototype.getItem = function (key) {
            if (key.startsWith('hapi.searchHistory.')) throw new DOMException('blocked', 'SecurityError')
            return getItem.call(this, key)
        }
        const setItem = Storage.prototype.setItem
        Storage.prototype.setItem = function (key, value) {
            if (key.startsWith('hapi.searchHistory.')) throw new DOMException('full', 'QuotaExceededError')
            return setItem.call(this, key, value)
        }
    })
    await page.goto(fixture)
    await optIn(page)
    const input = page.getByRole('searchbox')
    await input.fill('memory')
    await input.press('Enter')
    await input.fill('')
    await expect(recent(page).getByRole('button', { name: 'memory', exact: true })).toBeVisible()
    await go(page, 'Settings')
    await page.getByRole('button', { name: 'Clear search history' }).click()
    await expect(page.getByRole('button', { name: 'Clear search history' })).toBeDisabled()
})

test('malformed stored history recovers, whitespace is ignored and only the latest 20 queries remain', async ({ page }) => {
    await page.addInitScript(() => {
        const key = 'hapi.searchHistory.v1.' + encodeURIComponent(JSON.stringify([location.origin, 1, 'fixture']))
        localStorage.setItem(key, '{broken')
    })
    await page.goto(fixture)
    await optIn(page)
    const input = page.getByRole('searchbox')
    await input.fill('   ')
    await input.press('Enter')
    for (let index = 0; index < 22; index++) {
        await input.fill(`query-${index}`)
        await input.press('Enter')
    }
    expect((await history(page)).sessions).toHaveLength(20)
    expect((await history(page)).sessions.at(-1)).toBe('query-2')
    await input.fill('query-10')
    await input.press('Enter')
    expect((await history(page)).sessions.slice(0, 2)).toEqual(['query-10', 'query-21'])
})

test('another tab receives preference changes and history clearing', async ({ page, context }) => {
    await page.goto(fixture)
    await optIn(page)
    await page.getByRole('searchbox').fill('shared')
    await page.getByRole('searchbox').press('Enter')
    const other = await context.newPage()
    await other.goto(fixture)
    await other.getByRole('searchbox').focus()
    await expect(recent(other).getByRole('button', { name: 'shared', exact: true })).toBeVisible()
    await go(page, 'Settings')
    await page.getByRole('checkbox', { name: 'Search history', exact: true }).locator('..').click()
    await expect(recent(other)).toHaveCount(0)
    await page.getByRole('checkbox', { name: 'Search history', exact: true }).locator('..').click()
    await expect(recent(other)).toBeVisible()
    await page.getByRole('button', { name: 'Clear search history' }).click()
    await expect(recent(other)).toHaveCount(0)
    await other.close()
})

